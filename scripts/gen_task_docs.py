def main():
    rs = rows()
    ids = [r["id"] for r in rs]
    dup = {i for i in ids if ids.count(i) > 1}
    if dup:
        raise SystemExit(f"任务编号重复：{sorted(dup)}")
    known = set(ids)
    for r in rs:
        for d in [x for x in r["depends_on"].split(";") if x]:
            if d not in known:
                raise SystemExit(f"{r['id']} 依赖了不存在的任务 {d}")

    p1 = write_csv(rs)
    p2 = write_md(rs)
    print(f"已生成 {p1.relative_to(ROOT)}（{len(rs)} 行）")
    print(f"已生成 {p2.relative_to(ROOT)}（{len(rs)} 项，{sum(r['estimate_h'] for r in rs)} 人时）")


if __name__ == "__main__":
    main()
