def rows():
    out = []
    for tid, epic, title, owner, week, hours, prio, deps, acc, artifact in TASKS:
        start, end, milestone = WEEKS[week]
        out.append({
            "id": tid,
            "epic": epic,
            "epic_name": EPICS[epic],
            "title": title,
            "owner": owner,
            "week": week,
            "start": start,
            "end": end,
            "milestone": milestone,
            "estimate_h": hours,
            "priority": prio,
            "depends_on": ";".join(deps),
            "acceptance": "；".join(acc),
            "artifact": artifact,
            "labels": f"type/feat,{EPIC_AREA[epic]},priority/{prio}",
        })
    return out


def write_csv(rs):
    path = ROOT / "docs" / "tasks.csv"
    fields = ["id", "epic", "epic_name", "title", "owner", "week", "start", "end",
              "milestone", "estimate_h", "priority", "depends_on", "acceptance",
              "artifact", "labels"]
    with path.open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(rs)
    return path


